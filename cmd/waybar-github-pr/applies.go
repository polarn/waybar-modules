// PendingRoot is a terraform root that has landed on main but has not been
// applied since. In validio-internal/infra merging deliberately applies
// nothing — the README's recipe ends "Actions → Terraform apply → Run
// workflow → pick the root" — so this is the half of the lifecycle that is
// otherwise only tracked in someone's head.
type PendingRoot struct {
	Root       string `json:"root"`
	Repo       string `json:"repo"`
	Commits    int    `json:"commits"` // substantive commits since the last apply
	NewestSHA  string `json:"newest_sha"`
	NewestWhen string `json:"newest_when"`
	CompareURL string `json:"compare_url"`
	Workflow   string `json:"workflow"` // dispatched when the entry is picked
}

// planRelevant lists the file shapes terraform actually reads. A README or a
// CLAUDE.md inside a root cannot change a plan, so a commit touching only
// those is not a reason to apply anything.
//
// Deliberately narrow on the non-.tf entries: a bare ".yml" would match the
// .gitlab-ci.yml files sitting in every root before the CI migration, and a
// bare ".json" matches any data file. Only .env-exec.yaml earns its place,
// because it supplies the environment the provider credentials come from.
var planRelevant = []string{".tf", ".tfvars", ".tf.json", ".tftpl"}

func planRelevantFile(name string) bool {
	if filepath.Base(name) == ".env-exec.yaml" {
		return true
	}
	for _, ext := range planRelevant {
		if strings.HasSuffix(name, ext) {
			return true
		}
	}
	return false
}

// ---------------------------------------------------------------------------
// Telling a real change from a cosmetic one
// ---------------------------------------------------------------------------

// stripComment removes an HCL end-of-line comment, but only one that starts
// outside a string literal. Without the quote tracking, every line holding a
// URL loses everything from the "//" of "https://" and reads as changed —
// which matters here because the comments being edited are mostly URLs.
func stripComment(line string) string {
	var b strings.Builder
	inStr := false
	for i := 0; i < len(line); i++ {
		c := line[i]
		if inStr {
			if c == '\\' && i+1 < len(line) {
				b.WriteByte(c)
				b.WriteByte(line[i+1])
				i++
				continue
			}
			if c == '"' {
				inStr = false
			}
			b.WriteByte(c)
			continue
		}
		switch {
		case c == '"':
			inStr = true
			b.WriteByte(c)
		case c == '#':
			return normalizeSpace(b.String())
		case c == '/' && i+1 < len(line) && line[i+1] == '/':
			return normalizeSpace(b.String())
		default:
			b.WriteByte(c)
		}
	}
	return normalizeSpace(b.String())
}

func normalizeSpace(s string) string { return strings.Join(strings.Fields(s), " ") }

// substantive reports whether a patch changes anything terraform would act
// on. It strips comments from both sides and compares what is left.
//
// Everything uncertain is called substantive: a false "needs applying" costs
// a plan, a false "all clear" hides a real change. So an absent patch (too
// large, binary, renamed) and any block comment both count as substantive
// rather than being guessed at.
func substantive(patch string) bool {
	if patch == "" {
		return true
	}
	if strings.Contains(patch, "/*") || strings.Contains(patch, "*/") {
		return true
	}
	var minus, plus []string
	for _, line := range strings.Split(patch, "\n") {
		switch {
		case strings.HasPrefix(line, "---"), strings.HasPrefix(line, "+++"):
			continue
		case strings.HasPrefix(line, "-"):
			if s := stripComment(line[1:]); s != "" {
				minus = append(minus, s)
			}
		case strings.HasPrefix(line, "+"):
			if s := stripComment(line[1:]); s != "" {
				plus = append(plus, s)
			}
		}
	}
	sort.Strings(minus)
	sort.Strings(plus)
	if len(minus) != len(plus) {
		return true
	}
	for i := range minus {
		if minus[i] != plus[i] {
			return true
		}
	}
	return false
}

